// Plants for Dallas–Fort Worth gardens: natives of the Blackland Prairie and
// Cross Timbers, Texas natives from farther west and south, and vegetables,
// herbs, fruit and landscape plants that do well in North Central Texas heat
// and alkaline clay.
//
// Where the numbers come from:
// - Planting windows for vegetables are the Tarrant County AgriLife planting
//   calendar for North Central Texas, written as weeks from the DFW Airport
//   freeze normals (last Mar 12, first Nov 22; National Weather Service,
//   1991–2020), so they move with each garden's own frost dates. One decimal
//   reproduces the county dates to the day. Herb dates follow county advice in
//   words and are marked as estimates.
// - Water use for vegetables is FAO-56 (crop coefficient at full growth, table
//   12, and the share of water used before stress, table 22). Root zones are
//   garden watering depths: shallow 12 in, medium 18 in, deep 24 in.
// - Landscape water use follows Texas SmartScape's ratings for North Central
//   Texas (or the Native Plant Society of Texas where SmartScape has none),
//   turned into WUCOLS-style plant factors.
// - "native" means native to North Central Texas by the Native Plant Society of
//   Texas's ecoregion lists; "texas" marks Texas natives from elsewhere.
// - "est" lists the details that are best estimates rather than read from a
//   source, and the profile says so.
//
// Temperatures are written in °F, as the sources give them, and converted.

const F = (f) => (f == null ? null : Math.round((((f - 32) * 5) / 9) * 10) / 10);
const ROOTS = { shallow: 300, medium: 450, deep: 600 };
// [plant factor, share of water used before stress]
const WATER = {
  'very low': [0.15, 0.65],
  'very low to low': [0.22, 0.62],
  low: [0.3, 0.6],
  'low to medium': [0.4, 0.55],
  medium: [0.5, 0.5],
  'medium to high': [0.6, 0.45],
  high: [0.7, 0.4],
};

const win = (anchor, how, from, to, best) => ({ anchor, how, from, to, best: !!best });

// Planting seasons, in weeks from the average last freeze ('last') or first
// freeze ('first'). "best" marks the better of two windows.
const SEASONS = {
  // container trees: fall is best (Texas SmartScape), and through winter while dormant
  tree: [win('first', 'container', -6, 4, true), win('last', 'container', -12, 4)],
  // container shrubs, perennials and grasses: fall is best; late winter to spring works with extra water
  fall: [win('first', 'container', -6, 2, true), win('last', 'container', -8, 6)],
  // frost-tender perennials: after the last freeze, so they root before winter
  afterFrost: [win('last', 'container', 3, 10)],
  // fall-blooming perennials: early spring (Texas SmartScape)
  earlySpring: [win('last', 'container', -2, 6)],
  // cacti, agaves and yuccas root best in warm soil
  warmSpring: [win('last', 'container', 4, 14)],
  // bare-root fruit and nut trees while dormant; container trees in late fall
  bareroot: [win('last', 'bare-root', -13, -2, true), win('first', 'container', -3, 2)],
  // dormant blackberry plants and grapevines
  dormant: [win('last', 'bare-root', -10, 1)],
  // figs and pomegranates, once the hardest freezes are past
  lateWinter: [win('last', 'container', -3, 7)],
  // citrus in pots, set out after the last freeze
  citrus: [win('last', 'container', 0.5, 7)],
  // wildflower seed in fall, to sprout with fall rains and bloom in spring
  wildflower: [win('first', 'seed', -11, -2)],
  // cool-season annual flowers for fall-to-spring color
  coolAnnual: [win('first', 'transplant', -7, -2, true), win('last', 'transplant', -6, -2)],
  // warm-season lawns once the soil is warm (May–July in DFW)
  warmLawn: [win('last', 'sod or seed', 7, 17)],
  // tall fescue, seeded in early fall
  coolLawn: [win('first', 'seed', -9.5, -4.5)],
};

// How long and how often to water while a new plant settles in, where many plants share it.
const SETTLE = {
  tree: 'Water as needed for at least 18 months: soak slowly (soaker hose, several hours) whenever soil is dry 4–6 in deep, checking every 4–5 days in hot, dry weather; keep mulched (Texas SmartScape).',
  shrub:
    'Keep soil evenly moist but not wet through the first growing season; water when a probe shows the top 4–5 in are dry; keep 2–3 in of mulch (Texas SmartScape).',
  perennial:
    'Keep soil evenly moist (not wet) through the first growing season, checking 1 in deep; SmartScape rule of thumb for perennials: 1–2 in of water per week in summer, every 2 weeks in spring and fall, monthly in winter.',
  grass: 'Keep soil evenly moist through the first growing season, then water deeply and infrequently (Texas SmartScape).',
  succulent: 'Water every 1–2 weeks the first summer, then rarely.',
};

function edible(e) {
  const windows = [];
  if (e.spring) windows.push(win('last', ...e.spring));
  if (e.fall) windows.push(win('first', ...e.fall));
  if (e.plantRule) windows.push(...SEASONS[e.plantRule]);
  const perennial = e.season === 'perennial';
  return {
    life: perennial ? 'perennial' : 'annual',
    base: perennial ? 'shrubs' : 'veg',
    potBase: perennial ? 'shrubs' : 'veg',
    feedEvery: perennial ? 60 : 28,
    native: false,
    water: e.kc >= 0.9 ? 'high' : e.kc >= 0.6 ? 'medium' : e.kc >= 0.45 ? 'low to medium' : 'low',
    ...e,
    establish: e.settle ? SETTLE[e.settle] : e.establish,
    rootMm: ROOTS[e.roots] || 450,
    damageC: F(e.damageF),
    killC: F(e.killF),
    blossomC: F(e.blossomF),
    heatC: F(e.heatF),
    windows,
  };
}

const BASE = {
  tree: 'trees',
  shrub: 'shrubs',
  perennial: 'shrubs',
  grass: 'shrubs',
  groundcover: 'shrubs',
  vine: 'shrubs',
  succulent: 'natives',
  annual: 'flowers',
};
const POT = { shrub: 'shrubs', perennial: 'shrubs', grass: 'shrubs', groundcover: 'shrubs', vine: 'shrubs', succulent: 'natives', annual: 'flowers' };
const LAND_ROOTS = { tree: 600, shrub: 450, perennial: 300, grass: 450, groundcover: 200, vine: 450, succulent: 300, annual: 250, lawn: 200 };

function landscape(l) {
  const [kc, p] = WATER[l.water] || WATER.medium;
  const annual = l.type === 'annual';
  const windows = l.windows || SEASONS[l.plantRule] || SEASONS.fall;
  return {
    life: annual ? 'annual' : 'perennial',
    group: annual ? 'flower' : l.type,
    base: l.type === 'lawn' ? l.lawnBase : BASE[l.type],
    potBase: POT[l.type] || null,
    kc,
    p,
    rootMm: LAND_ROOTS[l.type] || 300,
    feedEvery: annual ? 28 : 0,
    frost: annual && l.season === 'warm' ? 'tender' : null,
    ...l,
    establish: l.settle ? SETTLE[l.settle] : l.establish,
    // warm-season annuals are hurt by frost itself
    damageC: F(l.damageF != null ? l.damageF : annual && l.season === 'warm' ? 32 : null),
    killC: F(l.coldF),
    heatC: F(l.heatF),
    windows: l.how ? windows.map((w) => ({ ...w, how: l.how })) : windows,
  };
}

